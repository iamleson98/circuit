#!/usr/bin/env python3
"""build_standalone.py — regenerate standalone/unode32u4-playground.tsx from
the real sources (lib/*.tsx + index.tsx), so the paste-into-the-browser copy
can never drift from the verified board.

Run from unode-32u4/:   python3 extras/build_standalone.py
"""
import re

LIBS = ["lib/atmega32u4.tsx", "lib/usb-micro-b.tsx", "lib/ferrite-bead.tsx"]
OUT = "standalone/unode32u4-playground.tsx"

HEADER = """/**
 * ═══════════════════════════════════════════════════════════════════════════
 *  μNode32U4 — bare ATmega32U4 USB dev board (SINGLE-FILE PLAYGROUND COPY)
 * ═══════════════════════════════════════════════════════════════════════════
 *  Paste this whole file into https://snippets.tscircuit.com (or any tscircuit
 *  playground) to view the PCB, schematic and 3D model interactively.
 *
 *  GENERATED by extras/build_standalone.py from lib/*.tsx + index.tsx —
 *  do not edit by hand; edit the sources and re-run the script.
 */
interface CommonLayoutProps {
  [key: string]: any
}
"""


def strip_imports(src: str) -> str:
    src = re.sub(r'^import [^\n]*\n', '', src, flags=re.M)
    return src.strip()


parts = [HEADER]
for path in LIBS:
    parts.append(strip_imports(open(path).read()))
parts.append(strip_imports(open("index.tsx").read()))
open(OUT, "w").write("\n\n".join(parts) + "\n")
print("wrote", OUT)
